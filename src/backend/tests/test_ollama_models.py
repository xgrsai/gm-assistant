"""Modelfile generator for the two Phase 4 Ollama models (`sft/ollama_models.py`): fake `ollama show` output."""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from sft import check_adapter as ca
from sft import ollama_models as om

BLOB = "C:/Users/1/.ollama/models/blobs/sha256-" + "a" * 64
# What `ollama show qwen2.5:3b --modelfile` prints (shortened): comments, FROM, a multi-line TEMPLATE whose text has a
# line that starts with FROM, PARAMETER stop tokens, and a multi-line LICENSE.
OFFICIAL = f'''# Modelfile generated by "ollama show"
# To build a new Modelfile based on this, replace FROM with:
# FROM qwen2.5:3b

FROM {BLOB}
TEMPLATE """{{{{- if .Messages }}}}
{{{{- range .Messages }}}}<|im_start|>{{{{ .Role }}}}
{{{{ .Content }}}}<|im_end|>
FROM inside the template is not an instruction
{{{{- end }}}}
<|im_start|>assistant
{{{{ end }}}}"""
SYSTEM You are Qwen, created by Alibaba Cloud. You are a helpful assistant.
PARAMETER stop <|im_start|>
PARAMETER stop <|im_end|>
LICENSE """Apache License
Version 2.0, January 2004
FROM here is licence text too
"""
'''

BASE_FILE, FT_FILE = ca.BASE_GGUF, ca.FT_GGUF


class FakeShow:
    def __init__(self, modelfile=OFFICIAL, error: Exception | None = None):
        self.modelfile, self.error, self.asked = modelfile, error, []

    def show(self, model):
        self.asked.append(model)
        if self.error:
            raise self.error
        return {"modelfile": self.modelfile, "template": "T"}


@pytest.fixture
def gguf_dir(tmp_path: Path) -> Path:
    d = tmp_path / "keeper-qwen25-3b-sft-v1"
    d.mkdir()
    (d / BASE_FILE).write_bytes(b"GGUF base")
    (d / FT_FILE).write_bytes(b"GGUF ft")
    return d


def run(gguf_dir: Path, fake: FakeShow, *extra: str) -> int:
    argv = ["modelfiles", "--gguf-dir", str(gguf_dir), "--ollama-url", "http://fake", *extra]
    return om.main(argv, client_factory=lambda url, timeout: fake)


def body(text: str) -> list[str]:
    """The Modelfile without the generator's header comment."""
    lines = text.split("\n")
    while lines and lines[0].startswith("# Generated by"):
        lines.pop(0)
    return lines


def test_only_the_from_line_changes():
    out = om.render_modelfile(OFFICIAL, FT_FILE, "note")
    want = [f"FROM ./{FT_FILE}" if line == f"FROM {BLOB}" else line for line in OFFICIAL.split("\n")]
    assert out.split("\n")[1:] == want  # the first line is the note; everything else is the official text
    assert out.startswith("# note\n") and out.endswith("\n") and not out.endswith("\n\n")


def test_from_like_lines_inside_quoted_blocks_are_kept():
    out = om.render_modelfile(OFFICIAL, FT_FILE, "n")
    assert "FROM inside the template is not an instruction" in out and "FROM here is licence text too" in out
    assert out.count(f"FROM ./{FT_FILE}") == 1
    assert "TEMPLATE" in out and "PARAMETER stop <|im_end|>" in out and "SYSTEM You are Qwen" in out


def test_crlf_text_becomes_lf():
    out = om.render_modelfile(OFFICIAL.replace("\n", "\r\n"), BASE_FILE, "n")
    assert "\r" not in out and f"FROM ./{BASE_FILE}" in out


@pytest.mark.parametrize(
    ("text", "message"),
    [
        (OFFICIAL + "ADAPTER ./adapter.gguf\n", "ADAPTER"),
        ("TEMPLATE x\nPARAMETER stop y\n", "0 FROM lines"),
        (OFFICIAL + "FROM ./another.gguf\n", "2 FROM lines"),
    ],
)
def test_unexpected_modelfiles_are_refused(text, message):
    with pytest.raises(ca.CheckError, match=message):
        om.render_modelfile(text, FT_FILE, "n")


def test_writes_two_modelfiles_that_differ_only_in_from(gguf_dir, capsys):
    fake = FakeShow()
    assert run(gguf_dir, fake) == 0
    assert fake.asked == ["qwen2.5:3b"]  # the official model is the single source
    base = (gguf_dir / "Modelfile.base").read_bytes()
    ft = (gguf_dir / "Modelfile.ft").read_bytes()
    assert b"\r" not in base + ft
    base_lines, ft_lines = base.decode("utf-8").split("\n"), ft.decode("utf-8").split("\n")
    assert len(base_lines) == len(ft_lines)
    differing = [(a, b) for a, b in zip(base_lines, ft_lines, strict=True) if a != b]
    assert differing[-1] == (f"FROM ./{BASE_FILE}", f"FROM ./{FT_FILE}") and len(differing) <= 2  # note line + FROM
    assert f"FROM ./{BASE_FILE}" in base_lines and f"FROM ./{FT_FILE}" in ft_lines
    assert not any(line.startswith("ADAPTER") for line in base_lines + ft_lines)
    out = capsys.readouterr().out
    assert f'cd "{gguf_dir}"' in out
    assert "ollama create qwen2.5-3b-selfq4:v1 -f Modelfile.base" in out
    assert "ollama create keeper-qwen25-3b:sft-v1 -f Modelfile.ft" in out
    assert "sft.check_adapter" in out


def test_tags_files_and_official_model_can_be_changed(gguf_dir, capsys):
    (gguf_dir / "b.gguf").write_bytes(b"x")
    (gguf_dir / "f.gguf").write_bytes(b"y")
    fake = FakeShow()
    code = run(gguf_dir, fake, "--official", "qwen2.5:7b", "--base-gguf", "b.gguf", "--ft-gguf", "f.gguf",
               "--base-tag", "my-base:v2", "--ft-tag", "my-ft:v2")  # fmt: skip
    assert code == 0 and fake.asked == ["qwen2.5:7b"]
    assert "FROM ./b.gguf" in (gguf_dir / "Modelfile.base").read_text(encoding="utf-8")
    assert "FROM ./f.gguf" in (gguf_dir / "Modelfile.ft").read_text(encoding="utf-8")
    out = capsys.readouterr().out
    assert "ollama create my-base:v2 -f Modelfile.base" in out and "ollama create my-ft:v2 -f Modelfile.ft" in out


def test_missing_gguf_writes_nothing(gguf_dir, capsys):
    (gguf_dir / FT_FILE).unlink()
    fake = FakeShow()
    assert run(gguf_dir, fake) == 2
    assert not (gguf_dir / "Modelfile.base").exists() and not (gguf_dir / "Modelfile.ft").exists()
    assert "merge_and_quantize" in capsys.readouterr().err and fake.asked == []


def test_ollama_errors_give_exit_code_2(gguf_dir, capsys):
    missing = ca.OllamaError("Ollama /api/show returned 404: model 'qwen2.5:3b' not found")
    assert run(gguf_dir, FakeShow(error=missing)) == 2
    assert "not found" in capsys.readouterr().err
    assert run(gguf_dir, FakeShow(modelfile="")) == 2
    assert "ollama pull qwen2.5:3b" in capsys.readouterr().err
    assert not (gguf_dir / "Modelfile.ft").exists()


def test_default_tags_match_the_checker():
    args = om.parse_args(["modelfiles"])
    assert (args.base_tag, args.ft_tag, args.official) == (ca.DEFAULT_BASE, ca.DEFAULT_FT, ca.DEFAULT_OFFICIAL)
    assert (args.base_gguf, args.ft_gguf) == (None, None)  # resolved from gguf_meta.json, else the Q4_K_M names


def test_gguf_names_come_from_gguf_meta_when_it_records_them(gguf_dir, capsys):
    (gguf_dir / "qwen2.5-3b-instruct.Q5_K_M.gguf").write_bytes(b"b")
    (gguf_dir / "keeper-qwen25-3b-sft-v1.Q5_K_M.gguf").write_bytes(b"f")
    meta = {"outputs": {"base": {"file": "qwen2.5-3b-instruct.Q5_K_M.gguf"},
                        "ft": {"file": "keeper-qwen25-3b-sft-v1.Q5_K_M.gguf"}}}  # fmt: skip
    (gguf_dir / ca.GGUF_META).write_text(json.dumps(meta), encoding="utf-8")
    assert run(gguf_dir, FakeShow()) == 0
    assert "FROM ./qwen2.5-3b-instruct.Q5_K_M.gguf" in (gguf_dir / "Modelfile.base").read_text(encoding="utf-8")
    assert "FROM ./keeper-qwen25-3b-sft-v1.Q5_K_M.gguf" in (gguf_dir / "Modelfile.ft").read_text(encoding="utf-8")
    assert ca.gguf_file_names(gguf_dir) == {"ft": "keeper-qwen25-3b-sft-v1.Q5_K_M.gguf",
                                            "base": "qwen2.5-3b-instruct.Q5_K_M.gguf"}  # fmt: skip
    (gguf_dir / ca.GGUF_META).write_text("{not json", encoding="utf-8")
    assert ca.gguf_file_names(gguf_dir) == {"ft": ca.FT_GGUF, "base": ca.BASE_GGUF}
