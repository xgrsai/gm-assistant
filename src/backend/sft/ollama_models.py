"""Modelfiles for the two Ollama models of Phase 4 (base and fine-tuned), built from the OFFICIAL qwen2.5:3b Modelfile.

    cd src/backend
    uv run python -m sft.ollama_models modelfiles --gguf-dir ../../adapters/keeper-qwen25-3b-sft-v1

This Ollama rejects `ADAPTER` (docs/critique.md C4 fallback), so the fine-tuned model is a GGUF with the LoRA merged in
and the base arm is a GGUF of the same Qwen2.5-3B-Instruct converted and quantized the same way
(`training/merge_and_quantize.py`). A GGUF imported with a bare `FROM` has no chat template, so both models must get the
template, the stop tokens and every other setting of the official `qwen2.5:3b` model. This command asks Ollama for that
model's Modelfile (`ollama show qwen2.5:3b --modelfile`, i.e. `/api/show`), replaces ONLY its `FROM` line with
`FROM ./<file>.gguf` and writes the result next to the GGUFs:

    Modelfile.base   FROM ./qwen2.5-3b-instruct.Q4_K_M.gguf              -> ollama create qwen2.5-3b-selfq4:v1
    Modelfile.ft     FROM ./keeper-qwen25-3b-sft-v1.Q4_K_M.gguf          -> ollama create keeper-qwen25-3b:sft-v1

so the two differ from each other, and from the official file, in that one line (`python -m sft.check_adapter` then
verifies the templates really are equal). It prints the two `ollama create` commands; it does not run them.
Exit codes: 0 written, 2 failed (Ollama down, no official model, GGUF missing, unexpected Modelfile).
"""

from __future__ import annotations

import argparse
import re
import sys
from collections.abc import Callable
from pathlib import Path

from server.settings import get_settings
from sft.check_adapter import (
    BASE_GGUF,
    DEFAULT_ADAPTER_DIR,
    DEFAULT_BASE,
    DEFAULT_FT,
    DEFAULT_OFFICIAL,
    FT_GGUF,
    GGUF_META,
    CheckError,
    OllamaApi,
    OllamaClient,
    OllamaError,
    gguf_file_names,
)

MODELFILE_BASE = "Modelfile.base"
MODELFILE_FT = "Modelfile.ft"
FROM_LINE = re.compile(r"FROM[ \t]+\S", re.I)
ADAPTER_LINE = re.compile(r"ADAPTER[ \t]", re.I)
BLOCK_QUOTE = '"""'  # TEMPLATE / SYSTEM / LICENSE texts span lines between triple quotes


def render_modelfile(official: str, gguf_name: str, note: str) -> str:
    """The official Modelfile text with its single `FROM` line replaced by `FROM ./<gguf_name>`.

    Lines inside a triple-quoted block (the template, the licence text) are never touched, even if one of them starts
    with the word FROM. An `ADAPTER` line, or a Modelfile without exactly one FROM line, is refused.
    """
    out: list[str] = []
    in_block = False
    from_lines = 0
    for line in official.replace("\r\n", "\n").split("\n"):
        if not in_block:
            if ADAPTER_LINE.match(line):
                raise CheckError(f"the official Modelfile has an ADAPTER line ({line!r}); expected a plain base model")
            if FROM_LINE.match(line):
                from_lines += 1
                out.append(f"FROM ./{gguf_name}")
                continue
        if line.count(BLOCK_QUOTE) % 2 == 1:
            in_block = not in_block
        out.append(line)
    if from_lines != 1:
        raise CheckError(f"the official Modelfile has {from_lines} FROM lines, expected exactly one")
    comment = "".join(f"# {text}\n" for text in note.splitlines())
    return comment + "\n".join(out).rstrip("\n") + "\n"


def official_modelfile(api: OllamaApi, official: str) -> str:
    text = api.show(official).get("modelfile")
    if not isinstance(text, str) or not text.strip():
        raise CheckError(f"Ollama returned no Modelfile for {official!r}; pull it with `ollama pull {official}`")
    return text


def create_commands(gguf_dir: Path, base_tag: str, ft_tag: str) -> list[str]:
    return [
        f'cd "{gguf_dir}"',
        f"ollama create {base_tag} -f {MODELFILE_BASE}",
        f"ollama create {ft_tag} -f {MODELFILE_FT}",
    ]


def write_modelfiles(
    api: OllamaApi, gguf_dir: Path, *, official: str, base_gguf: str, ft_gguf: str
) -> dict[str, Path]:
    """Write `Modelfile.base` and `Modelfile.ft` into `gguf_dir`; both GGUF files must already be there."""
    for name in (base_gguf, ft_gguf):
        if not (gguf_dir / name).is_file():
            raise CheckError(
                f"{gguf_dir / name} not found; download the output of training/merge_and_quantize.py into {gguf_dir}"
            )
    text = official_modelfile(api, official)
    written = {}
    for filename, gguf in ((MODELFILE_BASE, base_gguf), (MODELFILE_FT, ft_gguf)):
        note = (
            f"Generated by `python -m sft.ollama_models modelfiles` from `ollama show {official} --modelfile`: "
            f"only the FROM line is replaced (FROM ./{gguf}). Do not add ADAPTER, TEMPLATE or SYSTEM here."
        )
        path = gguf_dir / filename
        path.write_text(render_modelfile(text, gguf, note), encoding="utf-8", newline="\n")
        written[filename] = path
    return written


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = p.add_subparsers(dest="command", required=True)
    q = sub.add_parser("modelfiles", help="write Modelfile.base / Modelfile.ft and print the `ollama create` commands")
    q.add_argument("--gguf-dir", type=Path, default=DEFAULT_ADAPTER_DIR, help="directory with the two GGUF files")
    q.add_argument("--official", default=DEFAULT_OFFICIAL, help="library model whose Modelfile is the template")
    q.add_argument("--base-gguf", help=f"default: the name in {GGUF_META} of --gguf-dir, else {BASE_GGUF}")
    q.add_argument("--ft-gguf", help=f"default: the name in {GGUF_META} of --gguf-dir, else {FT_GGUF}")
    q.add_argument("--base-tag", default=DEFAULT_BASE, help="Ollama tag to create for the base model")
    q.add_argument("--ft-tag", default=DEFAULT_FT, help="Ollama tag to create for the fine-tuned model")
    q.add_argument("--ollama-url", help="default: OLLAMA_BASE_URL / http://localhost:11434")
    q.add_argument("--timeout", type=float, default=60.0)
    return p.parse_args(argv)


def main(argv: list[str] | None = None, *, client_factory: Callable[..., OllamaApi] | None = None) -> int:
    args = parse_args(argv)
    try:
        url = args.ollama_url or get_settings().ollama_base_url
        api = (client_factory or OllamaClient)(url, args.timeout)
        names = gguf_file_names(args.gguf_dir)
        written = write_modelfiles(
            api, args.gguf_dir, official=args.official, base_gguf=args.base_gguf or names["base"],
            ft_gguf=args.ft_gguf or names["ft"],
        )
    except (CheckError, OllamaError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr, flush=True)
        return 2
    for path in written.values():
        print(f"wrote {path}")
    print(f"Both files are the Modelfile of {args.official} with only the FROM line changed.")
    print("Next, run these one line at a time (PowerShell 5.1 has no &&):")
    for command in create_commands(args.gguf_dir, args.base_tag, args.ft_tag):
        print(f"  {command}")
    print("then cd back to src/backend and run: uv run python -m sft.check_adapter")
    return 0


if __name__ == "__main__":
    for stream in (sys.stdout, sys.stderr):  # the Windows console may be cp1251
        reconfigure = getattr(stream, "reconfigure", None)
        if reconfigure is not None:
            reconfigure(encoding="utf-8", errors="replace")
    raise SystemExit(main())
